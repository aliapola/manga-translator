package com.mangatranslator.app.translation

/**
 * تبدیل فارسی رسمی/کتابی (خروجی MyMemory) به فارسی محاوره‌ای با قاعده‌های ساده.
 * فقط سبک نوشتار را عوض می‌کند، نه معنی را. لیست قاعده‌ها را می‌توانید گسترش دهید.
 */
object PersianColloquial {

    private const val L = "\\u0600-\\u06FF\\u200c"          // حروف فارسی + نیم‌فاصله
    private const val ZWNJ = "\u200c"

    private fun wordRegex(formal: String) =
        Regex("(?<![$L])" + Regex.escape(formal) + "(?![$L])")

    // کلمه کامل -> محاوره‌ای
    private val words: List<Pair<Regex, String>> = listOf(
        "آن" to "اون", "آنجا" to "اونجا", "آنها" to "اونا", "آن${ZWNJ}ها" to "اونا",
        "اینها" to "اینا", "این${ZWNJ}ها" to "اینا", "او" to "اون",
        "را" to "رو", "مرا" to "منو", "ترا" to "تو رو",
        "اکنون" to "الان", "هم${ZWNJ}اکنون" to "همین الان", "بسیار" to "خیلی",
        "آری" to "آره", "خیر" to "نه", "هرگز" to "هیچ${ZWNJ}وقت",
        "چگونه" to "چطور", "زیرا" to "چون", "اما" to "ولی", "نیز" to "هم",
        "خانه" to "خونه", "نان" to "نون", "باران" to "بارون",
        "هستند" to "هستن", "نیستند" to "نیستن", "هستید" to "هستین", "نیستید" to "نیستین",
        "بودند" to "بودن", "بودید" to "بودین", "کردند" to "کردن", "شدند" to "شدن",
        "گفتند" to "گفتن", "رفتند" to "رفتن", "گرفتند" to "گرفتن", "دادند" to "دادن",
        "آمد" to "اومد", "آمدم" to "اومدم", "آمدی" to "اومدی", "آمدیم" to "اومدیم",
        "آمدند" to "اومدن", "آمده" to "اومده", "آمدهام" to "اومدم",
        "باشد" to "باشه", "باشند" to "باشن", "نباشد" to "نباشه", "نباشند" to "نباشن",
        "برود" to "بره", "بروم" to "برم", "بروید" to "برین", "بروند" to "برن",
        "بگوید" to "بگه", "بگویم" to "بگم", "بگویید" to "بگین", "بگویند" to "بگن",
        "بدهد" to "بده", "بدهم" to "بدم", "بدهید" to "بدین",
        "بیاید" to "بیاد", "بیایم" to "بیام", "بیایید" to "بیاین", "بیایند" to "بیان",
        "بکند" to "بکنه", "بکنند" to "بکنن", "بکنید" to "بکنین",
        "بشود" to "بشه", "بشوند" to "بشن", "نشود" to "نشه", "نکند" to "نکنه",
        "نرود" to "نره", "نگوید" to "نگه", "نیاید" to "نیاد",
        "بخواهد" to "بخواد", "نخواهد" to "نخواد", "بتواند" to "بتونه", "بداند" to "بدونه",
        "چیست" to "چیه", "کیست" to "کیه"
    ).map { (formal, colloq) -> wordRegex(formal) to colloq }

    private class V(val formal: String, val colloq: String, val zwnj: Boolean = true)

    // ریشه فعل‌های «می‌ …» / «نمی‌ …»
    private val verbs = listOf(
        V("خواهم", "خوام"), V("خواهی", "خوای"), V("خواهد", "خواد"),
        V("خواهیم", "خوایم"), V("خواهید", "خواین"), V("خواهند", "خوان"),
        V("دانم", "دونم"), V("دانی", "دونی"), V("داند", "دونه"),
        V("دانیم", "دونیم"), V("دانید", "دونین"), V("دانند", "دونن"),
        V("توانم", "تونم"), V("توانی", "تونی"), V("تواند", "تونه"),
        V("توانیم", "تونیم"), V("توانید", "تونین"), V("توانند", "تونن"),
        V("کند", "کنه"), V("کنند", "کنن"), V("کنید", "کنین"),
        V("رود", "ره"), V("روم", "رم"), V("روی", "ری"), V("رویم", "ریم"),
        V("روند", "رن"), V("روید", "رین"),
        V("شود", "شه"), V("شوند", "شن"), V("شوم", "شم"),
        V("دهد", "ده"), V("دهم", "دم"), V("دهند", "دن"), V("دهید", "دین"),
        V("گوید", "گه"), V("گویم", "گم"), V("گویند", "گن"), V("گویی", "گی"), V("گویید", "گین"),
        V("بیند", "بینه"), V("بینند", "بینن"),
        V("گیرد", "گیره"), V("گیرند", "گیرن"),
        V("افتد", "افته"), V("ماند", "مونه"),
        V("باشد", "باشه", zwnj = true),
        V("آید", "اد", zwnj = false), V("آیم", "ام", zwnj = false),
        V("آیند", "ان", zwnj = false), V("آیی", "ای", zwnj = false),
        V("آورد", "اره", zwnj = false), V("آورم", "ارم", zwnj = false)
    ).map { v ->
        val re = Regex("(?<![$L])(ن?)می$ZWNJ" + Regex.escape(v.formal) + "(?![$L])")
        val rep = "$1می" + (if (v.zwnj) ZWNJ else "") + v.colloq
        re to rep
    }

    private val miSpace = Regex("(?<![$L])(ن?)می\\s+(?=[\\u0600-\\u06FF])")
    private val isWord = Regex("([\\u0600-\\u06FF$ZWNJ]+)\\s+است(?![$L])")

    fun convert(input: String): String {
        if (input.isBlank()) return input
        var t = input.replace('ي', 'ی').replace('ك', 'ک')
        t = miSpace.replace(t) { it.groupValues[1] + "می" + ZWNJ }

        for ((re, rep) in words) t = re.replace(t, Regex.escapeReplacement(rep))
        for ((re, rep) in verbs) t = re.replace(t, rep)

        // «X است» -> «Xه» / «X‌ست»
        t = isWord.replace(t) { m ->
            val w = m.groupValues[1]
            when (w.last()) {
                'ه' -> w + ZWNJ + "ست"
                'ا', 'و' -> w + "ست"
                else -> w + "ه"
            }
        }
        return t
    }
}
